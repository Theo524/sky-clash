const assert=require('assert'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const b=fs.readFileSync(path.join(root,'assets/rin.vrm'));
assert.strictEqual(b.toString('ascii',0,4),'glTF');
assert.strictEqual(b.readUInt32LE(4),2);
assert.strictEqual(b.readUInt32LE(8),b.length);
const jl=b.readUInt32LE(12),j=JSON.parse(b.toString('utf8',20,20+jl));
assert(j.extensions?.VRM?.humanoid?.humanBones,'uploaded VRM0 avatar has humanoid bones');
assert(j.extensions.VRM.humanoid.humanBones.some(x=>x.bone==='head'));
assert.strictEqual(j.extensions.VRM.meta.author,'Theo');
assert.strictEqual(j.meshes.length,3);
assert(j.materials.some(m=>/Tops_01_CLOTH/.test(m.name)));
const binOffset=28+jl,binLen=b.readUInt32LE(20+jl);
assert.strictEqual(binOffset+binLen,b.length);
for(const im of j.images){let v=j.bufferViews[im.bufferView];assert(v.byteOffset+v.byteLength<=binLen);}
const changedTop=j.images[15],view=j.bufferViews[changedTop.bufferView];
assert.strictEqual(b.toString('hex',binOffset+view.byteOffset,binOffset+view.byteOffset+8),'89504e470d0a1a0a');
