const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'src/05-character-registry.js'),'utf8');
const reg=new Function(src+';return CharacterRegistry;')();
const k=reg.get('kairo_venn');
assert.equal(k.id,'kairo_venn');assert.equal(k.name,'Kairo Venn');
assert.equal(k.className,'Hybrid Martial Artist / Energy Warrior');
assert.equal(reg.can('kairo_venn','flight'),true,'Kairo must keep flight');
assert.equal(reg.can('kairo_venn','vanish'),true);
assert.equal(reg.can('kairo_venn','doubleJump'),false);
assert.equal(reg.move('kairo_venn','charged').id,'aether_breaker');
assert.equal(reg.move('kairo_venn','awakening').id,'stormheart');
assert.equal(reg.get('unknown').id,k.id,'fallback character');
const h=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'css/game.css'),'utf8');
const men=fs.readFileSync(path.join(root,'src/90-menus.js'),'utf8');
const game=fs.readFileSync(path.join(root,'src/95-game.js'),'utf8');
const camera=fs.readFileSync(path.join(root,'src/75-camera.js'),'utf8');
for(const key of ['dojoTools','dojoToggle','dojoPanel','dojoRivalMode','dojoResetBtn','dojoHomeBtn','pFighterName'])assert(h.includes('id="'+key+'"'),key+' missing');
assert(h.includes('class="dojo-tools hidden collapsed"'),'dojo panel closed by default');
assert(h.includes('aria-expanded="false"'),'accessibility state defaults closed');
assert(css.includes('.dojo-tools.collapsed .dojo-panel{display:none}'),'closed panel should occupy no space');
assert(css.includes('@media(max-width:700px)'),'mobile-specific compact sizes');
assert(men.includes("dojoTools.classList.toggle('collapsed')"),'tap opens panel');
assert(men.includes("document.addEventListener('pointerdown'"),'outside tap closes panel');
assert(game.includes("CharacterRegistry.get('kairo_venn')"),'Game loads Kairo profile');
assert(camera.includes('p.charging && p.chargeHeld'),'charge shake only active while charging');
console.log('V48 character registry / Kairo flight / compact dojo controls / camera rumble passed');
