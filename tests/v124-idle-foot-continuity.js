/* V124: preserve actual NORMAL IDLE foot direction and world-space
 * anchor points when first V108 prep tick is entered.
 */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const THREE=require('../js/vendor/three.min.js');
const V100=require('../js/v100-pose-authority.js');
const rad=n=>n*Math.PI/180;
const q=(node)=>node.getWorldQuaternion(new THREE.Quaternion());
const pt=node=>node.getWorldPosition(new THREE.Vector3());
let count=0;
for(const yaw of [0,.57,Math.PI,5.2]){
 const root=new THREE.Group();root.rotation.y=yaw;
 const scene=new THREE.Group();scene.rotation.y=Math.PI;root.add(scene);
 const pelvis=new THREE.Bone();pelvis.position.y=1;scene.add(pelvis);
 const bones={};
 for(const side of ['left','right']){
  const thigh=new THREE.Bone();pelvis.add(thigh);thigh.position.set(side==='left'?.12:-.12,-.10,0);
  const shin=new THREE.Bone();thigh.add(shin);shin.position.y=-.48;
  const shoe=new THREE.Bone();shin.add(shoe);shoe.position.set(0,-.43,.07);
  const toe=new THREE.Bone();shoe.add(toe);toe.position.set(0,-.09,-.16);
  bones[side+'Foot']=shoe;bones[side+'Toes']=toe;
 }
 const rig={f:{model:{root}},vrm:{scene,humanoid:{
  getNormalizedBoneNode:n=>bones[n]||null
 }}};
 for(const side of ['left','right'])
  bones[side+'Foot'].quaternion.setFromAxisAngle(new THREE.Vector3(0,1,0),
   rad(side==='left'?31:-24));
 scene.updateMatrixWorld(true);
 const anchored=V100.v124IdleFootAnchors(THREE,rig);
 assert.equal(anchored.length,2);
 for(const a of anchored){
  const foot=bones[a.side+'Foot'],toe=bones[a.side+'Toes'];
  assert(pt(foot).distanceTo(a.point)<1e-8);
  const direction=pt(toe).sub(pt(foot)).setY(0).normalize();
  assert(direction.angleTo(a.toeDirection)<1e-7);
  // Simulate first PREP frame generated by an older animation layer
  // that accidentally squares BOTH shoes and modifies one ankle.
  foot.quaternion.identity();
 }
 const forward=V100.realKairoForward(THREE,rig,{});
 V100.v122VisibleToeHeading(THREE,rig,forward,.2,{},anchored);
 scene.updateMatrixWorld(true);
 for(const a of anchored){
  const foot=bones[a.side+'Foot'],toe=bones[a.side+'Toes'];
  const heading=pt(toe).sub(pt(foot)).setY(0).normalize();
  assert(heading.angleTo(a.toeDirection)<.0001,
   'must aim back at each genuinely different idle toe heading');
  assert(pt(foot).distanceTo(a.point)<.0001,
   'world-Y foot heading must never teleport the anchored shoe position');
 }
 // Re-solve after different knee pitch; still use the same visible idle
 // toe direction, not a newly sampled symmetric v122 heading.
 for(const side of ['left','right'])
  bones[side+'Foot'].quaternion.setFromAxisAngle(new THREE.Vector3(1,0,0),.21);
 V100.v122VisibleToeHeading(THREE,rig,forward,.2,{},anchored);
 for(const a of anchored){
  const v=pt(bones[a.side+'Toes']).sub(pt(bones[a.side+'Foot'])).setY(0).normalize();
  assert(v.angleTo(a.toeDirection)<.0001,'heading survives crouch pitch');
 }
 count++;
}
const code=fs.readFileSync('js/v100-pose-authority.js','utf8');
const boot=fs.readFileSync('js/v66-game-boot.js','utf8');
assert(code.includes("const entryFeet=v124Entry?v124IdleFootAnchors(THREE,this.vrmRig):null;"),
 'must sample before legacy old.call, not after it');
assert(code.indexOf("const entryFeet=v124Entry?")<code.indexOf("old.call(this,dt);"));
assert(code.includes("if(entryFeet?.length===2)"));
assert(code.includes("v125 ? .20 : .20*stance.ready,status")&&
 code.includes("(v124||v125)?st.prepFeet:null"),
 'v124 must retain its measured original toe target behind its gate');
assert(code.includes("['v123','v124'].includes(params.get('jumpPreview'))"),
 'preserve expressive ascent from v123');
assert(boot.includes("e.src+='&idleFeet=124'"));
console.log('PASS V124: distinct original idle shoe angles, anchor positions and crouch foot heading on '+count+' actual VRM0 mirrored yaw rigs');
